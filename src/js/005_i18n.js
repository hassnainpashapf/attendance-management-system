/* ===== header language toggle: injected at runtime (11_layout.js untouched) ===== */
function i18nPaintToggle(){
  var wrap=document.getElementById('i18nToggle');
  if(!wrap) return;
  var btns=wrap.querySelectorAll('button');
  for(var i=0;i<btns.length;i++){
    var b=btns[i], on=b.getAttribute('data-lang')===I18N.lang;
    b.className='px-2.5 py-1.5 transition-colors '+(on?'bg-teal-600 text-white':'text-slate-500 hover:bg-slate-100');
    b.setAttribute('aria-pressed',on?'true':'false');
  }
}
function i18nMakeBtn(langCode,label){
  var b=document.createElement('button');
  b.type='button'; b.textContent=label;
  b.setAttribute('data-lang',langCode);
  b.title=(langCode==='ur'?'زبان':'Language');
  b.onclick=function(){ I18N.setLang(langCode); };
  return b;
}
function i18nMountToggle(){
  if(document.getElementById('i18nToggle')){ i18nPaintToggle(); return; }
  var hdr=document.querySelector('header');
  if(!hdr) return;
  var wrap=document.createElement('div');
  wrap.id='i18nToggle';
  wrap.className='flex items-center rounded-xl border border-slate-200 overflow-hidden text-xs font-bold shrink-0 bg-white';
  wrap.setAttribute('role','group');
  wrap.setAttribute('aria-label','Language');
  wrap.appendChild(i18nMakeBtn('en','EN'));
  wrap.appendChild(i18nMakeBtn('ur','اردو'));
  var av=document.getElementById('avatarBtn');
  var anchor=av?av.parentElement:null;
  if(anchor&&anchor.parentElement===hdr) hdr.insertBefore(wrap,anchor);
  else hdr.appendChild(wrap);
  i18nPaintToggle();
}
/* refresh header chrome strings after a language switch (shellHTML runs once) */
function i18nRefreshChrome(){
  var pb=document.getElementById('punchBtn');
  if(pb){ for(var i=0;i<pb.childNodes.length;i++){ var n=pb.childNodes[i]; if(n.nodeType===3&&n.nodeValue.trim()) n.nodeValue=I18N.t('c4.layout.punchInOut'); } }
  var ft=document.querySelector('footer');
  if(ft) ft.textContent=I18N.t('c4.layout.footer');
  var si=document.getElementById('stopImp');
  if(si){
    si.textContent=I18N.t('c4.layout.stopImpersonation');
    var sp=si.previousElementSibling;
    if(sp){ var nm=(window.Session&&window.Session.user&&window.Session.user.name)||''; sp.textContent=I18N.t('c4.layout.impersonating').replace('{name}',nm); }
  }
  var lo=document.getElementById('logout');
  if(lo){ lo.title=I18N.t('c4.layout.signOut'); lo.setAttribute('aria-label',I18N.t('c4.layout.signOut')); }
}
if(document.readyState==='loading') document.addEventListener('DOMContentLoaded',i18nMountToggle);
else i18nMountToggle();
/* shellHTML rebuilds <body> on login/logout/boot — re-mount when a header appears */
if(window.MutationObserver){
  try{
    new MutationObserver(function(){ i18nMountToggle(); }).observe(document.documentElement,{childList:true,subtree:true});
  }catch(e){}
}

/* ===== central re-render hook consumed by I18N.setLang =====
   Uses the app's central router when present; otherwise re-triggers the
   current hash route so every view (nav via labelKey, page chrome) re-renders
   in the new language. */
window.rerenderAll=function(){
  i18nPaintToggle();
  try{ i18nRefreshChrome(); }catch(e){}
  if(window.App&&typeof window.App.route==='function'){ window.App.route(); return; }
  var cur=location.hash||'#/dashboard';
  location.hash='#/i18n-'+Date.now();
  location.hash=cur;
};
